def decode(lst):
    return zlib.decompress(base64.urlsafe_b64decode(lst + "=" * (-len(lst) % 4)))

def encode(raw):
    return base64.urlsafe_b64encode(zlib.compress(raw, 9)).rstrip(b"=").decode()

out = {"source": DRAFT, "vectors": []}
for vector in VECTORS:
    bits, size = vector["bits"], vector["size"]
    raw = decode(vector["lst"])
    per = 8 // bits
    assert len(raw) * per == size, (bits, len(raw))
    mask = (1 << bits) - 1
    for index in range(size):
        value = (raw[index // per] >> ((index % per) * bits)) & mask
        assert value == vector["statuses"].get(index, 0), (bits, index, value)
    assert encode(raw) == vector["lst"], bits
    out["vectors"].append({
        "bits": bits,
        "size": size,
        "statuses": {str(index): value for index, value in sorted(vector["statuses"].items())},
        "lst": vector["lst"],
    })

json.dump(out, sys.stdout, indent=2)
sys.stdout.write("\n")
