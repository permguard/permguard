"""Indexes the normative blueprint for the traceability check (WP-7.13).

The blueprint lives beside this repository, in the workspace's knowledge base, so the CI of this
repository cannot read it. This script reads it where it is and writes what the check needs into
`crates/permguard-conformance/traceability/blueprint.json`:

- every H2 and H3 section of every document under `1-architecture` to `6-contracts`, with the
  anchor its links use (GitHub's: lower case, punctuation dropped, spaces to hyphens, a repeated
  heading suffixed `-1`, `-2`);
- every finding a register declares (`F`, `H`, `LANG`, `CEDAR`, `REGO`, `DOGWOOD`, `IFACE`): a table
  row whose first cell is the finding's id;
- every row of the legacy table of `10-implementation-plan/iteration-01.md` (a removed path, its
  fixture and its rollback boundary, or an alias the iteration keeps);
- the knowledge base's commit, so a stale index is visible.

    scripts/blueprint-index.py <knowledge>/permguard [--check]

`--check` writes nothing and exits 1 when the checked-in index is not what the blueprint gives.
"""

import json
import re
import subprocess
import sys
from pathlib import Path

FOLDERS = [
    "1-architecture",
    "2-control-plane",
    "3-data-plane",
    "4-languages",
    "5-command-line",
    "6-contracts",
]
HEADING = re.compile(r"^(#{2,3}) (.+?)\s*$")
FINDING = re.compile(r"^\|\s*`?((?:F|H|LANG|CEDAR|REGO|DOGWOOD|IFACE)-\d+)`?\s*\|")
OUT = Path(__file__).resolve().parent.parent / "crates/permguard-conformance/traceability/blueprint.json"


def slug(heading: str) -> str:
    text = heading.strip().lower()
    text = re.sub(r"[^\w\- ]", "", text)
    return text.replace(" ", "-")


def index(root: Path) -> dict:
    sections = []
    findings = {}
    for folder in FOLDERS:
        docs = sorted((root / folder).glob("*.md"))
        # A folder renamed or emptied would shrink the index, and the check would still pass.
        if not docs:
            raise SystemExit(f"{root / folder} holds no document: is {root} the blueprint?")
        for doc in docs:
            name = f"{folder}/{doc.name}"
            seen = {}
            fenced = False
            for line in doc.read_text(encoding="utf-8").splitlines():
                if line.lstrip().startswith(("```", "~~~")):
                    fenced = not fenced
                    continue
                if fenced:
                    continue
                heading = HEADING.match(line)
                if heading:
                    base = slug(heading.group(2))
                    count = seen.get(base, 0)
                    seen[base] = count + 1
                    anchor = base if count == 0 else f"{base}-{count}"
                    sections.append(
                        {
                            "id": f"{name}#{anchor}",
                            "level": len(heading.group(1)),
                            "heading": heading.group(2),
                        }
                    )
                    continue
                finding = FINDING.match(line)
                if finding and finding.group(1) not in findings:
                    findings[finding.group(1)] = name
    legacy = []
    plan = root / "10-implementation-plan/iteration-01.md"
    inside = False
    for line in plan.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            inside = line.strip() == "## Legacy paths and rollback boundaries"
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if not inside or not line.startswith("|") or len(cells) < 3:
            continue
        if cells[0] == "Legacy path removed" or set(cells[0]) <= {"-", " ", ":"}:
            continue
        legacy.append({"id": slug(cells[0].replace("`", "")), "path": cells[0], "removed_in": cells[1]})
    commit = subprocess.run(
        ["git", "-C", str(root), "log", "-1", "--format=%H", "--", *FOLDERS, "10-implementation-plan/iteration-01.md"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    if not re.fullmatch(r"[0-9a-f]{40}", commit):
        raise SystemExit(f"{root} names no commit of the blueprint: is it a git checkout?")
    return {
        "comment": "Generated by scripts/blueprint-index.py from the workspace knowledge base; "
        "do not edit by hand.",
        "knowledge_commit": commit,
        "sections": sections,
        "findings": [{"id": key, "register": findings[key]} for key in sorted(findings, key=order)],
        "legacy": legacy,
    }


def order(finding: str):
    prefix, number = finding.rsplit("-", 1)
    return (["F", "H", "LANG", "CEDAR", "REGO", "DOGWOOD", "IFACE"].index(prefix), int(number))


def main() -> int:
    args = [arg for arg in sys.argv[1:] if not arg.startswith("--")]
    if len(args) != 1:
        print(__doc__, file=sys.stderr)
        return 64
    text = json.dumps(index(Path(args[0])), indent=2, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is not what the blueprint gives: run {sys.argv[0]} {args[0]}", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
