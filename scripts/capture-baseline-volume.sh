# Captures the baseline volume (WP-7.7): the whole volume an all-in-one of the plan's baseline
# commit wrote, for the test that recovers it with today's binaries.
#
#   scripts/capture-baseline-volume.sh <baseline-bin-dir> <out-dir>
#
# `baseline-bin-dir` holds `permguard-all-in-one` and `permguard` built from commit `8390f612`
# (`git worktree add <dir> 8390f612 && cargo build --locked -p permguard-all-in-one -p permguard-cli`);
# the examples applied are the baseline's own `examples/basics` and `examples/dogwood-session-access`,
# read from that worktree, under its experimental configuration so the volume holds every store the
# baseline wrote: catalog, mirrors, decision spool and store, event journal and store, key rings,
# audit chain and secrets.
# `out-dir` receives `volume/`, the server's working directory as the baseline left it, with every
# `LOCK` emptied and empty directories removed, and `capture.json`, what was done to it.
#
# Run once; the capture is checked in. The keys and secrets inside are the development profile's
# autogenerated ones, made for this volume and nothing else.

set -euo pipefail

bin="${1:?usage: scripts/capture-baseline-volume.sh <baseline-bin-dir> <out-dir>}"
out="${2:?usage: scripts/capture-baseline-volume.sh <baseline-bin-dir> <out-dir>}"
worktree="$(cd "${bin}/../.." && pwd)"
server="${bin}/permguard-all-in-one"
cli="${bin}/permguard"

work="$(mktemp -d)"
pid=""
trap 'if [ -n "${pid}" ]; then kill "${pid}" 2>/dev/null || true; fi; rm -rf "${work}"' EXIT
mkdir -p "${work}/volume"

# The baseline's own experimental configuration, on ports nothing else uses and with its log in JSON.
sed -e 's/127.0.0.1:5443/127.0.0.1:25443/' -e 's/127.0.0.1:6443/127.0.0.1:26443/' \
    -e 's/127.0.0.1:7443/127.0.0.1:27443/' -e 's/format: terminal/format: json/' \
    -e 's/level: debug/level: info/' -e "s#working_dir: .volume/all-in-one#working_dir: ${work}/volume#" \
    -e 's#url: "http://127.0.0.1:6443"#url: "http://127.0.0.1:26443"#' \
    "${worktree}/crates/permguard-all-in-one/config.local-experimental.yml" >"${work}/config.yml"

env -u PERMGUARD_CONFIG "${server}" "${work}/config.yml" >"${work}/server.log" 2>&1 &
pid=$!
for _ in $(seq 1 120); do
    curl -fsS -o /dev/null http://127.0.0.1:25443/.well-known/server-configuration 2>/dev/null && break
    sleep 0.5
done

pg() { PERMGUARD_CONFIG="${work}/cli.yml" "${cli}" --control-endpoint http://127.0.0.1:26443 \
    --data-endpoint http://127.0.0.1:27443 "$@"; }

# Event trust, as the example's step 2: the data plane's public keys where the control plane reads them.
mkdir -p "${work}/volume/trust"
curl -fsS http://127.0.0.1:27443/data-plane/keys -o "${work}/volume/trust/data-plane-events.jwks"

pg zones create acme >/dev/null
pg ledgers create main-ledger --zone acme >/dev/null
cp -R "${worktree}/examples/basics" "${work}/basics"
rm -rf "${work}/basics/.permguard"
pg -w "${work}/basics" init basics --language cedar,rego >/dev/null
pg -w "${work}/basics" remote add origin http://127.0.0.1:26443 >/dev/null
pg -w "${work}/basics" checkout origin/acme/main-ledger >/dev/null
pg -w "${work}/basics" apply -m "the baseline volume" >/dev/null

pg ledgers create agent-governance --zone acme >/dev/null
cp -R "${worktree}/examples/dogwood-session-access" "${work}/dogwood"
rm -rf "${work}/dogwood/.permguard"
pg -w "${work}/dogwood" init agent-governance --language dogwood >/dev/null
pg -w "${work}/dogwood" remote add origin http://127.0.0.1:26443 >/dev/null
pg -w "${work}/dogwood" checkout origin/acme/agent-governance >/dev/null
pg -w "${work}/dogwood" apply -m "the baseline volume's temporal ledger" >/dev/null

# Served once the mirror verified and loaded the ledger; then every single request of the example,
# each decided and, with the decision log on, recorded and shipped.
answered=""
for _ in $(seq 1 120); do
    answered="$(pg -w "${work}/basics" -o json check -f requests/permit.json 2>/dev/null || true)"
    grep -q '"decision": *true' <<<"${answered}" && break
    sleep 1
done
grep -q '"decision": *true' <<<"${answered}" || {
    echo "the baseline never served the ledger: ${answered}" >&2
    tail -20 "${work}/server.log" >&2
    exit 1
}
for request in permit deny gateway-permit; do
    pg -w "${work}/basics" -o json check -f "requests/${request}.json" >"${work}/${request}.json"
done
# The temporal example's trace, as its steps 6 to 8 run it: a read before any login, the login,
# and the same read inside the window.
submit() {
    PERMGUARD_DEMO_ID=baseline-volume "${work}/dogwood/submit.sh" --endpoint http://127.0.0.1:27443 "$1"
}
temporal=""
for _ in $(seq 1 60); do
    temporal="$(submit requests/1-read-before-login.json 2>/dev/null || true)"
    grep -q '"outcome": *"decided"' <<<"${temporal}" && break
    sleep 1
done
grep -q '"outcome": *"decided"' <<<"${temporal}" || {
    echo "the baseline never served the temporal ledger: ${temporal}" >&2
    tail -20 "${work}/server.log" >&2
    exit 1
}
echo "${temporal}" >"${work}/before-login.json"
submit events/1-login-request.json >"${work}/login-request.json"
submit events/2-login-response.json >"${work}/login-response.json"
submit requests/2-read-inside-window.json >"${work}/inside-window.json"

# A batch every second: three intervals ship what was recorded.
sleep 4

kill -TERM "${pid}"
wait "${pid}" || true
pid=""

rm -rf "${out}"
mkdir -p "${out}"
cp -R "${work}/volume" "${out}/volume"
find "${out}/volume" -name LOCK -type f -exec sh -c ': >"$1"' _ {} \;
find "${out}/volume" -type d -empty -delete
jq -n --arg commit "$(git -C "${worktree}" rev-parse HEAD)" \
    --slurpfile permit "${work}/permit.json" --slurpfile deny "${work}/deny.json" \
    --slurpfile gateway "${work}/gateway-permit.json" \
    --slurpfile before "${work}/before-login.json" --slurpfile inside "${work}/inside-window.json" \
    '{commit: $commit, zone: "acme", ledger: "main-ledger", example: "examples/basics",
      decided: {permit: $permit[0].decision, deny: $deny[0].decision,
                "gateway-permit": $gateway[0].decision},
      temporal: {ledger: "agent-governance", example: "examples/dogwood-session-access",
                 "read-before-login": $before[0].decision, "read-inside-window": $inside[0].decision}}' \
    >"${out}/capture.json"
echo "captured $(find "${out}/volume" -type f | wc -l | tr -d ' ') files into ${out}"
